const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html','utf8');
const source = html.slice(html.indexOf('function customStatusCounts('),html.indexOf('function renderCustomStatusStats('));
const ctx = vm.createContext({normalizedStatus: s => s || 'جديد'});
vm.runInContext(source,ctx);
const rows = [{customStatus:'مهزش'},{customStatus:'مهزش'},{customStatus:'50%'},{customStatus:''},{}];
assert.equal(ctx.customStatusCounts(rows).get('مهزش'),2);
assert.equal(ctx.customStatusCounts(rows).get('50%'),1);
assert.equal(ctx.customStatusCounts([]).size,0);
assert.equal(ctx.customStatusCounts(rows.slice(2)).has('مهزش'),false);
assert.equal(ctx.matchesOrderFilter(rows[0],'all','مهزش'),true);
assert.equal(ctx.matchesOrderFilter(rows[2],'all','مهزش'),false);
assert.equal(ctx.matchesOrderFilter({status:'مكتمل'},'مكتمل',null),true);
assert.equal(ctx.customStatusCounts([{customStatus:'  راكح  '}]).get('راكح'),1);
assert.ok(html.includes('container.hidden = counts.size === 0'));
assert.ok(html.includes('renderCustomStatusStats();\n                filterOrders();'));
console.log('Custom status counts, zero removal, exact filtering and refresh passed.');
